// Generates TypeScript declarations from the native command interface definition.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
const [src, out] = process.argv.slice(2);
const iface = JSON.parse(readFileSync(resolve(src), "utf8"));
const lines = ["// GENERATED by tooling/gen-bindings.mjs — do not edit.", `export const abiVersion = ${iface.abiVersion} as const;`, "export interface Commands {"];
for (const c of iface.commands) lines.push(`  ${JSON.stringify(c.name)}: { capability: ${JSON.stringify(c.capability)}; args: ${c.args}; result: ${c.result} };`);
lines.push("}", `export const commandNames = ${JSON.stringify(iface.commands.map((c) => c.name))} as const;`, "");
mkdirSync(dirname(resolve(out)), { recursive: true });
writeFileSync(resolve(out), lines.join("\n"));
console.log(`generated ${out} (${iface.commands.length} commands)`);
