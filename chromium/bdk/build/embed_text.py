"""Writes a C++ header that holds a text file as a constant.

Usage: embed_text.py <input> <output.h> <constant name>

The page broker's Mojo bindings are compiled by Chromium's TypeScript build
and served by the bundled-page data source from the runtime itself, so the
bindings always match the runtime. Chromium's own WebUI pages ship such files
in resource packs, which would need the framework's packaging to change; a
header keeps the file inside //bdk.
"""

import os
import sys

DELIMITER = 'bdkembed'


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    source, output, name = argv[1:]
    with open(source, encoding='utf-8') as f:
        text = f.read()
    if ')' + DELIMITER + '"' in text:
        sys.stderr.write('%s contains the raw string delimiter\n' % source)
        return 1
    guard = 'BDK_GEN_' + ''.join(
        c if c.isalnum() else '_' for c in os.path.basename(output)).upper()
    with open(output, 'w', encoding='utf-8') as f:
        f.write('// Generated by //bdk/build/embed_text.py from %s. Do not edit.\n'
                % os.path.basename(source))
        f.write('#ifndef %s_\n#define %s_\n\n' % (guard, guard))
        f.write('namespace bdk {\n\n')
        f.write('inline constexpr char %s[] = R"%s(%s)%s";\n\n' %
                (name, DELIMITER, text, DELIMITER))
        f.write('}  // namespace bdk\n\n#endif  // %s_\n' % guard)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
