import { createHash } from "node:crypto";
import { SDK_PACKAGES, SDK_PREFIX } from "../../asset-sources.js";

/** The generated `@bdk` scope inside the output directory. */
export const SCOPE_DIRECTORY = "@bdk";

/** Written last, so its presence means the packages are complete: the digest of the SDK they were made from. */
export const SDK_DIGEST_FILE = "sdk.digest";

/** The files of one SDK package, as asset name to file name inside the package. */
export interface SdkPackage {
  /** `@bdk/internal`. */
  name: string;
  /** The package's asset names, `js/sdk/@bdk/internal/page.js`. */
  assets: readonly string[];
}

/** The SDK packages found among `names` (the asset names under `SDK_PREFIX`), in `SDK_PACKAGES` order. */
export function sdkPackages(names: readonly string[]): SdkPackage[] {
  return SDK_PACKAGES.map(({ name }) => ({
    name,
    assets: names.filter((asset) => asset.startsWith(`${SDK_PREFIX}${name}/`)),
  })).filter((p) => p.assets.length > 0);
}

/** The path of an asset inside the output directory: `@bdk/internal/page.js`. */
export function outputPath(asset: string): string {
  return asset.slice(SDK_PREFIX.length);
}

/** The digest of every SDK file's name and text, so a new `bdk` with a changed SDK regenerates. */
export function sdkDigest(files: ReadonlyMap<string, string>): string {
  const hash = createHash("sha256");
  for (const name of [...files.keys()].sort()) {
    hash.update(`${name}\0${files.get(name)}\0`);
  }
  return `sha256:${hash.digest("hex")}`;
}

/**
 * The `package.json` of one generated package: ES modules, and an `exports` entry for each module that has
 * a `.d.ts` beside it (`index` is the package itself). `@bdk/internal` also exports `./app`, the
 * per-application declarations, for `tsc`.
 */
export function packageJson(pkg: SdkPackage, version: string): string {
  const modules = pkg.assets
    .map((asset) => asset.slice(`${SDK_PREFIX}${pkg.name}/`.length))
    .filter((file) => file.endsWith(".js"))
    .map((file) => file.slice(0, -".js".length))
    .filter((module) => pkg.assets.includes(`${SDK_PREFIX}${pkg.name}/${module}.d.ts`))
    .sort();
  const exports: Record<string, unknown> = {};
  for (const module of modules) {
    exports[module === "index" ? "." : `./${module}`] = {
      types: `./${module}.d.ts`,
      default: `./${module}.js`,
    };
  }
  if (pkg.name === "@bdk/internal") exports["./app"] = { types: "./app.d.ts" };
  return `${JSON.stringify(
    {
      name: pkg.name,
      version,
      private: true,
      type: "module",
      description: "Generated by `bdk build codegen`. Do not edit.",
      ...(modules.includes("index") ? { main: "./index.js", types: "./index.d.ts" } : {}),
      exports,
    },
    null,
    2,
  )}\n`;
}
