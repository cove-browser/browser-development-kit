import type { ConstantGroup, Definitions } from "./model.js";
import type { Registry, RegistryEntry } from "./registry.js";
import { macroFragment } from "./validate.js";

const COMMENT_WIDTH = 98;

/** A block comment in the style clang-format keeps: one line if it fits, else ` * ` continuations. */
function comment(text: string): string[] {
  if (text.length + 6 <= COMMENT_WIDTH) return [`/* ${text} */`];
  const lines: string[] = [];
  let current = "";
  for (const word of text.split(" ")) {
    if (current !== "" && current.length + 1 + word.length + 3 > COMMENT_WIDTH) {
      lines.push(current);
      current = word;
    } else {
      current = current === "" ? word : `${current} ${word}`;
    }
  }
  lines.push(current);
  return lines.map((line, index) => {
    const open = index === 0 ? "/* " : " * ";
    return index === lines.length - 1 ? `${open}${line} */` : `${open}${line}`;
  });
}

function constantValue(group: ConstantGroup, value: string | number): string {
  if (group.kind === "string") return JSON.stringify(value);
  if (group.kind === "flags") return `0x${(value as number).toString(16)}u`;
  return `${value}u`;
}

function identifierSection(
  title: string,
  prefix: string,
  entries: readonly RegistryEntry[],
): string[] {
  const live = entries.filter((entry) => entry.retired !== true);
  if (live.length === 0) return [];
  return [
    ...comment(title),
    ...live.map((entry) => `#define ${prefix}${macroFragment(entry.name)} ${entry.id}u`),
    "",
  ];
}

/** Renders `bdk_ids.h`. Same definitions and registry in, same bytes out. */
export function renderHeader(definitions: Definitions, registry: Registry): string {
  const body: string[] = [];
  for (const group of definitions.constants) {
    if (group.comment !== undefined) body.push(...comment(group.comment));
    for (const [suffix, value] of group.values) {
      body.push(`#define ${group.prefix}${suffix} ${constantValue(group, value)}`);
    }
    body.push("");
  }
  body.push(
    ...identifierSection(
      "Command identifiers (bdk_invoke). Assigned once from interface/ids.json, never reused.",
      "BDK_COMMAND_",
      registry.commands,
    ),
    ...identifierSection(
      "Event identifiers (bdk_subscribe). Assigned once from interface/ids.json, never reused.",
      "BDK_EVENT_",
      registry.events,
    ),
  );

  const lines = [
    ...comment(
      "BDK C ABI: identifiers. Generated by packages/js/codegen from the definitions in packages/core/interface " +
        "and packages/core/interface/ids.json (assigned identifiers). Do not edit. " +
        "Regenerate with: pnpm exec nx run js-codegen:codegen",
    ),
    "#ifndef BDK_IDS_H_",
    "#define BDK_IDS_H_",
    "",
    "#include <stdint.h>",
    "",
    "#ifdef __cplusplus",
    'extern "C" {',
    "#endif",
    "",
    ...body,
    "#ifdef __cplusplus",
    "}",
    "#endif",
    "",
    "#endif /* BDK_IDS_H_ */",
  ];
  return `${lines.join("\n")}\n`;
}
