import type { Command, Definitions, EventDefinition, FieldDefinition } from "./model.js";
import {
  elementOf,
  fieldLine,
  isOptional,
  pascal,
  pascalName,
  renderType,
  Usage,
} from "./ts-types.js";

/** Where the `@bdk/internal` modules are written, relative to `packages/core`. */
export const TYPESCRIPT_DIR = "../js/internal/src";

/** The directory the generated modules are reported by, from the repository root. */
export const TYPESCRIPT_REPORT_DIR = "packages/js/internal/src";

/**
 * Namespaces with no generated module: `runtime` is `@bdk/internal/page`, written by hand because the page
 * is created from `runtime.caller`.
 */
export const HAND_WRITTEN_NAMESPACES: readonly string[] = ["runtime"];

/** Namespaces that share another's module (javascript-api.md section 3). */
const MODULE_OF_NAMESPACE: Readonly<Record<string, string>> = { cookies: "privacy" };

/**
 * Events a page must not receive as the broker sends them. `cookies.changed` carries a `CookieValue`, and
 * a page never reads cookie values (`cookies.values` is refused to pages).
 */
const WITHHELD_EVENTS: readonly string[] = ["cookies.changed"];

/** Argument types that are narrower than the definition's `string`: the keys of the settings store. */
const ARGUMENT_TYPES: Readonly<Record<string, string>> = {
  "settings.get.key": "SettingKey",
  "settings.getMany.keys": "SettingKey[]",
  "settings.describe.key": "SettingKey",
  "settings.set.key": "SettingKey",
  "settings.reset.key": "SettingKey",
};

export const HEAD = [
  "// Generated by packages/js/codegen from packages/core/interface. Do not edit.",
  "// Regenerate with: pnpm exec nx run js-codegen:codegen",
  "// biome-ignore-all lint: generated file",
  "// biome-ignore-all format: generated file",
  "",
];

/** `types.ts`: every struct, enum and alias of the definitions, and the JSON value type. */
export function renderTypes(definitions: Definitions): string {
  const usage = new Usage();
  const body = definitions.types.flatMap((type) => renderType(type, usage));
  return `${[
    ...HEAD,
    "/** Any value JSON can carry. */",
    "export type JsonValue =",
    "  | string",
    "  | number",
    "  | boolean",
    "  | null",
    "  | JsonValue[]",
    "  | { [key: string]: JsonValue };",
    "",
    ...body,
  ]
    .join("\n")
    .replace(/\n+$/, "")}\n`;
}

// MARK: commands

export interface Segments {
  readonly namespace: string;
  readonly group: string | undefined;
  readonly method: string;
}

export function segments(name: string): Segments {
  const [namespace, ...rest] = name.split(".");
  const method = rest.pop();
  if (namespace === undefined || method === undefined || rest.length > 1) {
    throw new Error(`${name}: a command name has a namespace, an optional group and a method`);
  }
  return { namespace, group: rest[0], method };
}

function argumentsType(command: Command, usage: Usage): string | undefined {
  const fields = command.args.filter((field) => !(command.paginated && field.name === "cursor"));
  if (fields.length === 0) return undefined;
  const parts = fields.map((field) => {
    const override = ARGUMENT_TYPES[`${command.name}.${field.name}`];
    if (override === undefined) return fieldLine(usage, field, false);
    usage.local.add("SettingKey");
    return `${field.name}${isOptional(field.type) ? "?" : ""}: ${override};`;
  });
  return `{ ${parts.join(" ")} }`;
}

function documentation(command: Command): string[] {
  const lines = [`\`${command.name}\`. Needs the capability \`${command.capability ?? "none"}\`.`];
  if (command.paginated) lines.push("Follows the cursor: iterate to read every page.");
  if (command.requires.includes("gesture")) {
    lines.push(
      "Call it from a user gesture in the page, or it rejects with `capability.gestureRequired`.",
    );
  }
  if (command.requires.includes("authentication")) {
    lines.push("Asks the operating system to authenticate before it runs.");
  }
  return lines;
}

/** A doc comment, on one line when there is one line of text. */
function jsdoc(lines: readonly string[]): string[] {
  if (lines.length === 1) return [`/** ${lines[0]} */`];
  return ["/**", ...lines.map((line) => ` * ${line}`), " */"];
}

interface Rendered {
  readonly declarations: string[];
  readonly method: string[];
}

function renderCommand(command: Command, usage: Usage): Rendered {
  const { method } = segments(command.name);
  const name = JSON.stringify(command.name);
  const args = argumentsType(command, usage);
  const allOptional = command.args.every((field) => isOptional(field.type));
  usage.types.add("CallOptions");
  const parameters = [
    ...(args === undefined ? [] : [`args${allOptional ? "?" : ""}: ${args}`]),
    "options?: CallOptions",
  ].join(", ");
  const argument = args === undefined ? "{}" : allOptional ? "args ?? {}" : "args";
  const declarations: string[] = [];
  const lines: string[] = jsdoc(documentation(command));
  const result = command.result;
  const fields = typeof result === "string" ? undefined : result;

  if (command.paginated) {
    const items = fields?.find((field) => field.name === "items");
    const item = items === undefined ? undefined : elementOf(items.type);
    if (item === undefined) {
      throw new Error(`${command.name}: a paginated command's result needs an "items" array`);
    }
    usage.values.add("paginate");
    const type = usage.type(item);
    lines.push(
      `${method}(${parameters}): AsyncIterable<${type}> {`,
      `  return paginate<${type}>(${name}, ${argument}, options);`,
      "},",
    );
    return { declarations, method: lines };
  }

  usage.values.add("invoke");
  if (result === "void" || (fields !== undefined && fields.length === 0)) {
    lines.push(
      `async ${method}(${parameters}): Promise<void> {`,
      `  await invoke(${name}, ${argument}, options);`,
      "},",
    );
  } else if (typeof result === "string") {
    const type = usage.type(result);
    lines.push(
      `${method}(${parameters}): Promise<${type}> {`,
      `  return invoke<${type}>(${name}, ${argument}, options);`,
      "},",
    );
  } else if (result.length === 1) {
    const only = result[0] as FieldDefinition;
    const type = usage.type(only.type);
    lines.push(
      `async ${method}(${parameters}): Promise<${type}> {`,
      `  const result = await invoke<{ ${only.name}: ${type} }>(${name}, ${argument}, options);`,
      `  return result.${only.name};`,
      "},",
    );
  } else {
    const type = `${pascalName(command.name)}Result`;
    declarations.push(
      `export interface ${type} {`,
      ...result.map((field) => `  ${fieldLine(usage, field, true)}`),
      "}",
      "",
    );
    lines.push(
      `${method}(${parameters}): Promise<${type}> {`,
      `  return invoke<${type}>(${name}, ${argument}, options);`,
      "},",
    );
  }
  return { declarations, method: lines };
}

function renderEvent(event: EventDefinition, namespace: string, usage: Usage): Rendered {
  const name = event.name.slice(namespace.length + 1);
  const method = `on${pascal(name)}`;
  const payload = event.payload;
  const declarations: string[] = [];
  let listener: string;
  if (typeof payload === "string") {
    listener = `(payload: ${usage.type(payload)}) => void`;
  } else if (payload.length === 0) {
    listener = "() => void";
  } else {
    const type = `${pascalName(event.name)}Event`;
    declarations.push(
      `export interface ${type} {`,
      ...payload.map((field) => `  ${fieldLine(usage, field, true)}`),
      "}",
      "",
    );
    listener = `(payload: ${type}) => void`;
  }
  usage.types.add("EventFilter");
  usage.types.add("Subscription");
  usage.values.add("subscribe");
  return {
    declarations,
    method: [
      `/** \`${event.name}\`. Needs the capability \`${event.capability}\`. */`,
      `${method}(listener: ${listener}, filter?: EventFilter): Subscription {`,
      `  return subscribe(${JSON.stringify(event.name)}, listener as (payload: unknown) => void, filter);`,
      "},",
    ],
  };
}

/** The object literal of one namespace: its commands, nested one level for a group, and its events. */
function renderNamespace(
  namespace: string,
  commands: readonly Command[],
  events: readonly EventDefinition[],
  usage: Usage,
): string[] {
  const declarations: string[] = [];
  const body: string[] = [];
  const indent = (lines: readonly string[], by: string) => lines.map((line) => `${by}${line}`);

  const direct = commands.filter((command) => segments(command.name).group === undefined);
  const groups = [...new Set(commands.map((command) => segments(command.name).group))].filter(
    (group): group is string => group !== undefined,
  );
  for (const command of direct) {
    const rendered = renderCommand(command, usage);
    declarations.push(...rendered.declarations);
    body.push(...indent(rendered.method, "  "));
  }
  for (const group of groups) {
    body.push(`  ${group}: {`);
    for (const command of commands.filter((c) => segments(c.name).group === group)) {
      const rendered = renderCommand(command, usage);
      declarations.push(...rendered.declarations);
      body.push(...indent(rendered.method, "    "));
    }
    body.push("  },");
  }
  for (const event of events) {
    const rendered = renderEvent(event, namespace, usage);
    declarations.push(...rendered.declarations);
    body.push(...indent(rendered.method, "  "));
  }
  return [...declarations, `export const ${namespace} = {`, ...body, "};", ""];
}

function renderImports(usage: Usage): string[] {
  const protocolTypes = ["CallOptions", "EventFilter", "Subscription"];
  const callTypes = [...usage.types].filter((name) => protocolTypes.includes(name)).sort();
  const dataTypes = [...usage.types].filter((name) => !protocolTypes.includes(name)).sort();
  const lines: string[] = [];
  if (usage.local.size > 0) {
    lines.push(`import type { ${[...usage.local].sort().join(", ")} } from "./app-settings.js";`);
  }
  if (callTypes.length > 0) lines.push(`import type { ${callTypes.join(", ")} } from "./call.js";`);
  if (usage.values.size > 0) {
    lines.push(`import { ${[...usage.values].sort().join(", ")} } from "./call.js";`);
  }
  if (dataTypes.length > 0)
    lines.push(`import type { ${dataTypes.join(", ")} } from "./types.js";`);
  return lines;
}

/** The module a namespace is written to. */
function moduleOf(namespace: string): string {
  return MODULE_OF_NAMESPACE[namespace] ?? namespace;
}

function renderModule(
  definitions: Definitions,
  namespaces: readonly string[],
): { text: string; types: readonly string[] } {
  const usage = new Usage();
  const body: string[] = [];
  for (const namespace of namespaces) {
    const commands = definitions.commands.filter(
      (command) =>
        command.callers.includes("page") && segments(command.name).namespace === namespace,
    );
    const events = definitions.events.filter(
      (event) => event.name.startsWith(`${namespace}.`) && !WITHHELD_EVENTS.includes(event.name),
    );
    body.push(...renderNamespace(namespace, commands, events, usage));
  }
  const protocolTypes = ["CallOptions", "EventFilter", "Subscription"];
  const reexported = [...usage.types]
    .filter((name) => !protocolTypes.includes(name) && name !== "JsonValue")
    .sort();
  const lines = [
    ...HEAD,
    ...renderImports(usage),
    "",
    ...(reexported.length > 0 ? [`export type { ${reexported.join(", ")} };`, ""] : []),
    ...body,
  ];
  return { text: `${lines.join("\n").replace(/\n+$/, "")}\n`, types: reexported };
}

/** `metadata.ts`: the capability each command and event needs, for the mock transport. */
function renderMetadata(definitions: Definitions, commands: readonly Command[]): string {
  const live = definitions.events.filter((event) => !WITHHELD_EVENTS.includes(event.name));
  return `${[
    ...HEAD,
    "/** The capability each command a page may call needs; null for a command that needs none. */",
    "export const COMMAND_CAPABILITIES: Readonly<Record<string, string | null>> = {",
    ...commands.map(
      (command) =>
        `  ${JSON.stringify(command.name)}: ${JSON.stringify(command.capability ?? null)},`,
    ),
    "};",
    "",
    "/** The capability each event a page may subscribe to needs. */",
    "export const EVENT_CAPABILITIES: Readonly<Record<string, string>> = {",
    ...live.map((event) => `  ${JSON.stringify(event.name)}: ${JSON.stringify(event.capability)},`),
    "};",
  ].join("\n")}\n`;
}

/**
 * Renders the `@bdk/internal` modules, as file name to text: `types.ts` (every named type), `metadata.ts`
 * and one module per namespace a page can call, with a typed function per command and an `on…` function
 * per event. Same definitions in, same bytes out.
 */
export function renderTypescriptModules(definitions: Definitions): Record<string, string> {
  const pageCommands = definitions.commands.filter(
    (command) =>
      command.callers.includes("page") &&
      !HAND_WRITTEN_NAMESPACES.includes(segments(command.name).namespace),
  );
  const metadataCommands = definitions.commands.filter((command) =>
    command.callers.includes("page"),
  );
  const namespaces = [
    ...new Set(pageCommands.map((command) => segments(command.name).namespace)),
  ].sort();
  const modules = new Map<string, string[]>();
  for (const namespace of namespaces) {
    const module = moduleOf(namespace);
    modules.set(module, [...(modules.get(module) ?? []), namespace]);
  }
  const files: Record<string, string> = {
    "types.ts": renderTypes(definitions),
    "metadata.ts": renderMetadata(definitions, metadataCommands),
  };
  for (const [module, own] of [...modules].sort(([a], [b]) => (a < b ? -1 : 1))) {
    files[`${module}.ts`] = renderModule(definitions, own).text;
  }
  return files;
}
