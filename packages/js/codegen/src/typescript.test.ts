import { describe, expect, it } from "vitest";
import { build, type Inputs } from "./generate.js";
import { abi, history, type Json, mutate } from "./test-support.js";

const POLICY = JSON.stringify({ neverForPages: ["contents.*"], neverForSessions: [] });
const ALL = ["swift", "page", "session"];

function command(name: string, extra: Json = {}): Json {
  return {
    name,
    capability: `${name.split(".")[0]}.read`,
    callers: ALL,
    profile: "required",
    args: {},
    result: "void",
    ...extra,
  };
}

function extras(): Json[] {
  return [
    {
      namespace: "settings",
      since: 1,
      types: { SettingInfo: { key: "string", default: "json", allowed: "json?" } },
      commands: [
        command("settings.get", { args: { key: "string" }, result: { value: "json" } }),
        command("settings.getMany", { args: { keys: "string[]" }, result: { values: "json" } }),
        command("settings.describe", { args: { key: "string" }, result: "SettingInfo" }),
      ],
      events: [
        {
          name: "settings.changed",
          capability: "settings.read",
          payload: { key: "string", source: "ChangeSource" },
        },
      ],
    },
    {
      namespace: "cookies",
      since: 1,
      types: { CookieValue: { name: "string", value: "string" } },
      commands: [
        command("cookies.list", { result: { items: "string[]" } }),
        command("cookies.getValues", {
          capability: "cookies.values",
          callers: ["swift", "session"],
          result: { items: "CookieValue[]" },
        }),
      ],
      events: [
        {
          name: "cookies.changed",
          capability: "cookies.read",
          payload: { cookie: "CookieValue", removed: "bool" },
        },
      ],
    },
    {
      namespace: "privacy",
      since: 1,
      types: { PrivacyType: { enum: ["history", "cookies"] } },
      commands: [
        command("privacy.clear", {
          requires: ["gesture"],
          progress: true,
          args: { types: "PrivacyType[]", range: "TimeRange?" },
        }),
      ],
      events: [{ name: "privacy.refreshed", capability: "privacy.read", payload: {} }],
    },
    {
      namespace: "passwords",
      since: 1,
      commands: [command("passwords.check", { result: { checked: "int", flagged: "int" } })],
    },
    {
      namespace: "autofill",
      since: 1,
      commands: [
        command("autofill.cards.list", { result: { items: "string[]" } }),
        command("autofill.cards.remove", { args: { id: "string" } }),
      ],
    },
    {
      namespace: "runtime",
      since: 1,
      types: { RuntimeInfo: { bdkVersion: "string" } },
      commands: [
        command("runtime.info", { profile: "none", result: "RuntimeInfo" }),
        command("runtime.caller", { capability: undefined, profile: "none" }),
      ],
    },
    {
      namespace: "swiftonly",
      since: 1,
      commands: [command("swiftonly.run", { callers: ["swift"] })],
    },
  ];
}

function inputs(files: Json[] = extras(), historyFile: Json = history()): Inputs {
  return {
    abiVersion: 1,
    definitions: [
      { file: "history.json", text: JSON.stringify(historyFile) },
      { file: "abi.json", text: JSON.stringify(abi()) },
      ...files.map((file) => ({ file: `${file.namespace}.json`, text: JSON.stringify(file) })),
    ],
    policy: POLICY,
    registry: undefined,
  };
}

const modules = (files?: Json[], historyFile?: Json): Record<string, string> =>
  build(inputs(files, historyFile)).typescript;

describe("the TypeScript modules", () => {
  it("are byte-stable and independent of the order of the files", () => {
    const first = modules();
    expect(modules()).toEqual(first);
    const reversed = { ...inputs(), definitions: [...inputs().definitions].reverse() };
    expect(build(reversed).typescript).toEqual(first);
  });

  it("make one module per namespace a page can call, cookies inside privacy, and no module for runtime", () => {
    expect(Object.keys(modules()).sort()).toEqual([
      "autofill.ts",
      "history.ts",
      "metadata.ts",
      "passwords.ts",
      "privacy.ts",
      "settings.ts",
      "types.ts",
    ]);
  });

  it("start with the generated-file markers and are excluded from the formatters", () => {
    for (const text of Object.values(modules())) {
      expect(
        text.startsWith(
          "// Generated by packages/js/codegen from packages/core/interface. Do not edit.\n",
        ),
      ).toBe(true);
      expect(text).toContain("// Regenerate with: pnpm exec nx run js-codegen:codegen\n");
      expect(text).toContain("// biome-ignore-all lint: generated file\n");
      expect(text).toContain("// biome-ignore-all format: generated file\n");
    }
  });
});

describe("types.ts", () => {
  const types = modules()["types.ts"] as string;

  it("declares the JSON value type", () => {
    expect(types).toContain("export type JsonValue =");
  });

  it("writes a struct as an interface; an optional field also admits null", () => {
    expect(types).toContain(
      [
        "export interface TimeRange {",
        "  start?: number | null;",
        "  end?: number | null;",
        "}",
      ].join("\n"),
    );
    expect(types).toContain(
      [
        "export interface HistoryEntry {",
        "  url: string;",
        "  title: string;",
        "  lastVisit: number;",
        "}",
      ].join("\n"),
    );
  });

  it("writes an enum as a union of strings and maps the primitives", () => {
    expect(types).toContain('export type ChangeSource = "user" | "sync";');
    expect(types).toContain("  default: JsonValue;");
    expect(types).toContain("  allowed?: JsonValue | null;");
  });
});

describe("a module", () => {
  it("wraps a command in a function of one args object and the call options", () => {
    const out = modules()["history.ts"] as string;
    expect(out).toContain('import { invoke, paginate, subscribe } from "./call.js";');
    expect(out).toContain(
      'import type { CallOptions, EventFilter, Subscription } from "./call.js";',
    );
    expect(out).toContain(
      'import type { ChangeSource, HistoryEntry, TimeRange } from "./types.js";',
    );
    expect(out).toContain("export type { ChangeSource, HistoryEntry, TimeRange };");
  });

  it("returns an AsyncIterable of the items for a paginated command and drops the cursor argument", () => {
    const out = modules()["history.ts"] as string;
    expect(out).toContain(
      "  search(args: { text: string; range?: TimeRange; limit?: number; }, options?: CallOptions): AsyncIterable<HistoryEntry> {",
    );
    expect(out).toContain('    return paginate<HistoryEntry>("history.search", args, options);');
    expect(out).toContain("Follows the cursor: iterate to read every page.");
  });

  it("takes no args, only options, when there are none, and resolves void", () => {
    const out = modules()["history.ts"] as string;
    expect(out).toContain("  async deleteAll(options?: CallOptions): Promise<void> {");
    expect(out).toContain('    await invoke("history.deleteAll", {}, options);');
  });

  it("makes args optional when every field is optional", () => {
    const optional = mutate(history(), (file) => {
      ((file.commands as Json[])[1] as Json).args = { note: "string?" };
    });
    const out = modules(undefined, optional)["history.ts"] as string;
    expect(out).toContain("async deleteAll(args?: { note?: string; }, options?: CallOptions)");
    expect(out).toContain('await invoke("history.deleteAll", args ?? {}, options);');
  });

  it("unwraps a single-field result", () => {
    const out = modules()["settings.ts"] as string;
    expect(out).toContain(
      "  async get(args: { key: SettingKey; }, options?: CallOptions): Promise<JsonValue> {",
    );
    expect(out).toContain(
      'const result = await invoke<{ value: JsonValue }>("settings.get", args, options);',
    );
    expect(out).toContain("    return result.value;");
  });

  it("types the setting keys as SettingKey", () => {
    const out = modules()["settings.ts"] as string;
    expect(out).toContain('import type { SettingKey } from "./app-settings.js";');
    expect(out).toContain("async getMany(args: { keys: SettingKey[]; }");
    expect(out).toContain(
      "describe(args: { key: SettingKey; }, options?: CallOptions): Promise<SettingInfo>",
    );
  });

  it("names a result of several fields as an interface of the module", () => {
    const out = modules()["passwords.ts"] as string;
    expect(out).toContain(
      [
        "export interface PasswordsCheckResult {",
        "  checked: number;",
        "  flagged: number;",
        "}",
      ].join("\n"),
    );
    expect(out).toContain("check(options?: CallOptions): Promise<PasswordsCheckResult>");
  });

  it("nests a group of commands under its name", () => {
    const out = modules()["autofill.ts"] as string;
    expect(out).toContain("export const autofill = {\n  cards: {");
    expect(out).toContain('invoke<{ items: string[] }>("autofill.cards.list", {}, options)');
    expect(out).toContain('await invoke("autofill.cards.remove", args, options);');
  });

  it("documents the capability, the gesture and progress through the call options", () => {
    const out = modules()["history.ts"] as string;
    expect(out).toContain("`history.deleteAll`. Needs the capability `history.write`.");
    expect(out).toContain(
      "Call it from a user gesture in the page, or it rejects with `capability.gestureRequired`.",
    );
  });

  it("writes on<Event> for each event, with a named interface for an inline payload", () => {
    const out = modules()["history.ts"] as string;
    expect(out).toContain(
      [
        "export interface HistoryVisitedEvent {",
        "  entry: HistoryEntry;",
        "  source: ChangeSource;",
        "}",
      ].join("\n"),
    );
    expect(out).toContain(
      "  onVisited(listener: (payload: HistoryVisitedEvent) => void, filter?: EventFilter): Subscription {",
    );
    expect(out).toContain(
      '    return subscribe("history.visited", listener as (payload: unknown) => void, filter);',
    );
  });

  it("gives an event with no payload a listener with no parameter", () => {
    const out = modules()["privacy.ts"] as string;
    expect(out).toContain(
      "onRefreshed(listener: () => void, filter?: EventFilter): Subscription {",
    );
  });

  it("leaves out a command a page cannot call, and the cookie values event", () => {
    const privacy = modules()["privacy.ts"] as string;
    expect(privacy).toContain("export const cookies = {");
    expect(privacy).toContain("async list(");
    expect(privacy).not.toContain("getValues");
    expect(privacy).not.toContain("onChanged");
    expect(privacy).toContain("export const privacy = {");
    expect(Object.keys(modules())).not.toContain("swiftonly.ts");
  });
});

describe("metadata.ts", () => {
  const metadata = modules()["metadata.ts"] as string;

  it("lists the capability of each command a page may call, runtime.caller with none", () => {
    expect(metadata).toContain('  "history.search": "history.read",');
    expect(metadata).toContain('  "history.deleteAll": "history.write",');
    expect(metadata).toContain('  "runtime.caller": null,');
    expect(metadata).toContain('  "runtime.info": "runtime.read",');
    expect(metadata).not.toContain("cookies.getValues");
    expect(metadata).not.toContain("swiftonly.run");
  });

  it("lists the capability of each event", () => {
    expect(metadata).toContain('  "history.visited": "history.read",');
    expect(metadata).not.toContain("cookies.changed");
  });
});

describe("a changed definition", () => {
  it("changes the module and nothing else", () => {
    const before = modules();
    const changed = mutate(history(), (file) => {
      ((file.commands as Json[])[1] as Json).name = "history.clear";
    });
    const after = modules(undefined, changed);
    expect(after["history.ts"]).not.toBe(before["history.ts"]);
    expect(after["history.ts"]).toContain('"history.clear"');
    expect(after["metadata.ts"]).not.toBe(before["metadata.ts"]);
    expect(after["settings.ts"]).toBe(before["settings.ts"]);
    expect(after["types.ts"]).toBe(before["types.ts"]);
  });

  it("changes the types when a field is added", () => {
    const changed = mutate(history(), (file) => {
      ((file.types as Json).HistoryEntry as Json).visitCount = "int";
    });
    expect(modules(undefined, changed)["types.ts"]).toContain("  visitCount: number;");
    expect(modules()["types.ts"]).not.toContain("visitCount");
  });
});
