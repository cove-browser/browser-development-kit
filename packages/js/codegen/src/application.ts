import { createHash } from "node:crypto";
import { InterfaceError, type Issue } from "./issue.js";
import type { FieldDefinition, TypeDefinition } from "./model.js";
import { PRIMITIVES } from "./model.js";
import { fieldLine, isOptional, renderType, Usage } from "./ts-types.js";

/** The application's commands, events and settings, written by `BDKDeclarations.write(to:)`. */
export const COMMANDS_FILE = "bdk.commands.json";

/** The configuration the build resolved from `bdk.toml`. */
export const RESOLVED_FILE = "bdk.resolved.json";

/** Where the per-application declarations are written, relative to the generated JavaScript root. */
export const APP_DECLARATIONS_PATH = "@bdk/internal/app.d.ts";
export const APP_ENVIRONMENT_PATH = "@bdk/env.d.ts";
/** The same declarations for scripts, merged into `@bdk/automation`. */
export const APP_AUTOMATION_PATH = "@bdk/automation/app.d.ts";

/** The text of the two files the per-application declarations come from. */
export interface ApplicationInputs {
  readonly commands: string;
  readonly resolved: string;
}

const FORMAT_VERSION = 1;
const DIGEST_PREFIX = "// Input digest: ";
const DIGEST_LINE = /^\/\/ Input digest: (sha256:[0-9a-f]{64})$/m;
const TYPE_NAME = /^[A-Z][a-zA-Z0-9]*$/;
const COMMAND_NAME = /^app(\.[a-z][a-zA-Z0-9]*)+$/;
const TYPE_EXPRESSION = /^([A-Za-z][A-Za-z0-9]*)(\[\])?(\?)?$/;
const SETTING_TYPES: Readonly<Record<string, string>> = {
  boolean: "boolean",
  number: "number",
  string: "string",
  array: "JsonValue[]",
  object: "{ [key: string]: JsonValue }",
  json: "JsonValue",
};

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** The digest of an input as it is written in a generated file: `sha256:` and 64 hexadecimal digits. */
export function digestOf(text: string): string {
  return `sha256:${createHash("sha256").update(text).digest("hex")}`;
}

/** The digest a generated file records, or undefined when it has none. */
export function readDigest(generated: string): string | undefined {
  return DIGEST_LINE.exec(generated)?.[1];
}

/** True when a generated file was not made from exactly this input: the build must regenerate it. */
export function isStale(generated: string, input: string): boolean {
  return readDigest(generated) !== digestOf(input);
}

function header(source: string, input: string): string[] {
  return [
    `// Generated by @bdk/codegen from ${source}. Do not edit.`,
    "// Regenerate with: bdk build codegen",
    `${DIGEST_PREFIX}${digestOf(input)}`,
    "// biome-ignore-all lint: generated file",
    "// biome-ignore-all format: generated file",
    "",
  ];
}

// MARK: parsing and checking

interface Collector {
  readonly file: string;
  readonly issues: Issue[];
  add(path: string, message: string): void;
}

function collector(file: string): Collector {
  const issues: Issue[] = [];
  return { file, issues, add: (path, message) => issues.push({ file, path, message }) };
}

function parse(text: string, found: Collector): unknown {
  try {
    return JSON.parse(text);
  } catch (error) {
    found.add("$", `invalid JSON: ${error instanceof Error ? error.message : String(error)}`);
    return undefined;
  }
}

interface Shape {
  /** A type expression such as `Note[]`, `void`, or the fields of an inline struct. */
  readonly value: string | readonly FieldDefinition[];
}

interface Declared {
  readonly name: string;
  readonly input: Shape;
  readonly output: Shape;
}

interface DeclaredEvent {
  readonly name: string;
  readonly payload: Shape;
}

interface DeclaredSetting {
  readonly key: string;
  readonly type: string;
}

interface Declarations {
  readonly commands: readonly Declared[];
  readonly events: readonly DeclaredEvent[];
  readonly settings: readonly DeclaredSetting[];
  readonly types: readonly TypeDefinition[];
}

function checkExpression(found: Collector, path: string, expression: unknown, known: Set<string>) {
  if (typeof expression !== "string") return found.add(path, "must be a type expression string");
  const match = TYPE_EXPRESSION.exec(expression);
  if (match === null)
    return found.add(path, `${JSON.stringify(expression)} is not a type expression`);
  const base = match[1] as string;
  if (!PRIMITIVES.includes(base) && !known.has(base)) {
    found.add(path, `unknown type ${JSON.stringify(base)}`);
  }
}

function fieldsOf(body: Json): FieldDefinition[] {
  return Object.entries(body).map(([name, type]) => ({ name, type: String(type) }));
}

function readShape(
  found: Collector,
  path: string,
  value: unknown,
  known: Set<string>,
  allowVoid: boolean,
): Shape {
  if (isObject(value)) {
    for (const [name, type] of Object.entries(value))
      checkExpression(found, `${path}.${name}`, type, known);
    return { value: fieldsOf(value) };
  }
  if (value === "void" && allowVoid) return { value: "void" };
  checkExpression(found, path, value, known);
  return { value: typeof value === "string" ? value : "json" };
}

/** One list of entries and where it is in the file, for the paths of issues. */
interface EntryList {
  readonly entries: readonly Json[];
  readonly path: string;
}

/** Merges the `types` of every entry; two entries may declare a type, but only identically. */
function readTypes(found: Collector, lists: readonly EntryList[]): TypeDefinition[] {
  const merged = new Map<string, { definition: TypeDefinition; text: string; path: string }>();
  for (const { entries, path: listPath } of lists) {
    for (const [index, entry] of entries.entries()) {
      const types = entry.types;
      if (types === undefined) continue;
      const path = `${listPath}[${index}].types`;
      if (!isObject(types)) {
        found.add(path, "must be an object");
        continue;
      }
      for (const [name, body] of Object.entries(types)) {
        const here = `${path}.${name}`;
        if (
          !TYPE_NAME.test(name) ||
          PRIMITIVES.includes(name.toLowerCase()) ||
          name === "JsonValue"
        ) {
          found.add(here, `${JSON.stringify(name)} is not a usable type name`);
          continue;
        }
        let definition: TypeDefinition;
        if (typeof body === "string") definition = { name, kind: "alias", target: body };
        else if (isObject(body) && Array.isArray(body.enum) && Object.keys(body).length === 1) {
          definition = { name, kind: "enum", values: body.enum.map(String) };
        } else if (isObject(body)) definition = { name, kind: "struct", fields: fieldsOf(body) };
        else {
          found.add(here, "must be a struct, an enum or an alias");
          continue;
        }
        const text = JSON.stringify(body);
        const first = merged.get(name);
        if (first === undefined) merged.set(name, { definition, text, path: here });
        else if (first.text !== text) {
          found.add(here, `type ${JSON.stringify(name)} is declared differently at ${first.path}`);
        }
      }
    }
  }
  const known = new Set(merged.keys());
  const types = [...merged.values()];
  for (const { definition, path } of types) {
    const targets =
      definition.kind === "alias"
        ? [definition.target]
        : definition.kind === "struct"
          ? definition.fields.map((field) => field.type)
          : [];
    for (const target of targets) checkExpression(found, path, target, known);
  }
  return types.map(({ definition }) => definition).sort((a, b) => (a.name < b.name ? -1 : 1));
}

/** The entries of a list, an invalid one replaced by `{}` so that paths keep their index. */
function entriesOf(found: Collector, json: Json, key: string): Json[] {
  const list = json[key];
  if (list === undefined) return [];
  if (!Array.isArray(list)) {
    found.add(`$.${key}`, "must be an array");
    return [];
  }
  return list.map((entry, index) => {
    if (isObject(entry)) return entry;
    found.add(`$.${key}[${index}]`, "must be an object");
    return {};
  });
}

function checkName(found: Collector, path: string, name: unknown, kind: string, seen: Set<string>) {
  if (typeof name !== "string" || !COMMAND_NAME.test(name)) {
    found.add(`${path}.name`, `${kind} names start with "app." and have lower-camel-case segments`);
  } else if (seen.has(name)) found.add(`${path}.name`, `duplicate ${kind} ${JSON.stringify(name)}`);
  else seen.add(name);
}

function readDeclarations(commandsText: string): { declarations: Declarations; issues: Issue[] } {
  const found = collector(COMMANDS_FILE);
  const json = parse(commandsText, found);
  const empty: Declarations = { commands: [], events: [], settings: [], types: [] };
  if (json === undefined) return { declarations: empty, issues: found.issues };
  if (!isObject(json)) {
    found.add("$", "must be an object");
    return { declarations: empty, issues: found.issues };
  }
  for (const key of Object.keys(json)) {
    if (!["version", "commands", "events", "settings"].includes(key))
      found.add(`$.${key}`, "unknown field");
  }
  if (json.version !== FORMAT_VERSION) found.add("$.version", `must be ${FORMAT_VERSION}`);

  const commandEntries = entriesOf(found, json, "commands");
  const eventEntries = entriesOf(found, json, "events");
  const types = readTypes(found, [
    { entries: commandEntries, path: "$.commands" },
    { entries: eventEntries, path: "$.events" },
  ]);
  const known = new Set(types.map((type) => type.name));

  const seen = new Set<string>();
  const commands = commandEntries.map((entry, index): Declared => {
    const path = `$.commands[${index}]`;
    checkName(found, path, entry.name, "command", seen);
    return {
      name: String(entry.name),
      input: readShape(found, `${path}.args`, entry.args ?? "void", known, true),
      output: readShape(found, `${path}.result`, entry.result ?? "void", known, true),
    };
  });
  const seenEvents = new Set<string>();
  const events = eventEntries.map((entry, index): DeclaredEvent => {
    const path = `$.events[${index}]`;
    checkName(found, path, entry.name, "event", seenEvents);
    return {
      name: String(entry.name),
      payload: readShape(found, `${path}.payload`, entry.payload ?? "void", known, true),
    };
  });
  const seenSettings = new Set<string>();
  const settings = entriesOf(found, json, "settings").flatMap((entry, index): DeclaredSetting[] => {
    const path = `$.settings[${index}]`;
    const key = entry.key;
    if (typeof key !== "string" || !COMMAND_NAME.test(key)) {
      found.add(`${path}.key`, 'setting keys start with "app." and have lower-camel-case segments');
    } else if (seenSettings.has(key))
      found.add(`${path}.key`, `duplicate setting ${JSON.stringify(key)}`);
    else seenSettings.add(key);
    const type = entry.type;
    if (typeof type !== "string" || SETTING_TYPES[type] === undefined) {
      found.add(`${path}.type`, `must be one of ${Object.keys(SETTING_TYPES).join(", ")}`);
    }
    // A setting hidden from pages is not reachable from a page, so it has no key there.
    if (entry.exposedToPages !== true) return [];
    return typeof key === "string" && typeof type === "string" ? [{ key, type }] : [];
  });
  return { declarations: { commands, events, settings, types }, issues: found.issues };
}

interface Environment {
  readonly routes: readonly string[];
  readonly scheme: string;
}

function readEnvironment(resolvedText: string): { environment: Environment; issues: Issue[] } {
  const found = collector(RESOLVED_FILE);
  const json = parse(resolvedText, found);
  const environment: Environment = { routes: [], scheme: "" };
  if (json === undefined) return { environment, issues: found.issues };
  if (!isObject(json)) {
    found.add("$", "must be an object");
    return { environment, issues: found.issues };
  }
  const names = new Set<string>();
  for (const key of ["routes", "aliases"]) {
    const table = json[key];
    if (isObject(table)) for (const name of Object.keys(table)) names.add(name);
    else if (table !== undefined || key === "routes") found.add(`$.${key}`, "must be an object");
  }
  const browser = json.browser;
  const scheme = isObject(browser) ? browser.internal_scheme : undefined;
  if (typeof scheme !== "string" || scheme === "") {
    found.add("$.browser.internal_scheme", "must be the internal scheme, a non-empty string");
  }
  return {
    environment: { routes: [...names].sort(), scheme: typeof scheme === "string" ? scheme : "" },
    issues: found.issues,
  };
}

// MARK: rendering

function shapeType(usage: Usage, shape: Shape, nullable: boolean, empty: string): string {
  const value = shape.value;
  if (typeof value === "string") {
    if (value === "void") return empty;
    return `${usage.type(value)}${isOptional(value) ? " | null" : ""}`;
  }
  if (value.length === 0) return empty;
  return `{ ${value.map((field) => fieldLine(usage, field, nullable)).join(" ")} }`;
}

/** The package whose modules a set of declarations is merged into. */
type Target = "@bdk/internal" | "@bdk/automation";

function renderDeclarations(declarations: Declarations, input: string, target: Target): string {
  const usage = new Usage();
  const types = declarations.types.flatMap((type) => renderType(type, usage));

  const commands = declarations.commands.map(
    (command) =>
      `    ${JSON.stringify(command.name)}: { input: ${shapeType(usage, command.input, false, "Record<string, never>")}; output: ${shapeType(usage, command.output, true, "void")} };`,
  );
  const events = declarations.events.map(
    (event) =>
      `    ${JSON.stringify(event.name)}: ${shapeType(usage, event.payload, true, "Record<string, never>")};`,
  );
  const settings = declarations.settings.map(({ key, type }) => {
    return `    ${JSON.stringify(key)}: ${SETTING_TYPES[type]};`;
  });
  const usesJson =
    usage.types.has("JsonValue") ||
    declarations.settings.some(({ type }) => SETTING_TYPES[type]?.includes("JsonValue"));
  const augment = (module: string, name: string, members: readonly string[]) =>
    members.length === 0
      ? []
      : [`declare module "${module}" {`, `  interface ${name} {`, ...members, "  }", "}", ""];

  return `${[
    ...header(COMMANDS_FILE, input),
    ...(usesJson ? [`import type { JsonValue } from "${target}/types";`, ""] : []),
    "export {};",
    "",
    ...types,
    ...augment(`${target}/commands`, "AppCommands", commands),
    ...augment(`${target}/events`, "AppEvents", events),
    // Scripts reach settings through the `settings` service namespace, whose keys are strings.
    ...(target === "@bdk/internal"
      ? augment("@bdk/internal/app-settings", "AppSettings", settings)
      : []),
  ]
    .join("\n")
    .replace(/\n+$/, "")}\n`;
}

function renderEnvironment(environment: Environment, input: string): string {
  const routes =
    environment.routes.length === 0
      ? "never"
      : environment.routes.map((name) => JSON.stringify(name)).join(" | ");
  return `${[
    ...header(RESOLVED_FILE, input),
    "/** Every route name and alias of the application, as `page.url` takes them. */",
    `export type RouteName = ${routes};`,
    "",
    "/** The branded scheme of the application's internal pages. */",
    `export type InternalScheme = ${JSON.stringify(environment.scheme)};`,
  ].join("\n")}\n`;
}

/**
 * Renders the per-application declarations as relative path to file text: `@bdk/internal/app.d.ts` (the
 * application's commands, events and settings, merged into `@bdk/internal`), `@bdk/automation/app.d.ts` (its
 * commands and events, merged into `@bdk/automation`) and `@bdk/env.d.ts` (route names and the internal
 * scheme). Each file records the digest of its input; see `readDigest`. Throws an
 * `InterfaceError` with every problem found in either input. Same input in, same bytes out.
 */
export function generateApplication(inputs: ApplicationInputs): Record<string, string> {
  const declared = readDeclarations(inputs.commands);
  const environment = readEnvironment(inputs.resolved);
  const issues = [...declared.issues, ...environment.issues];
  if (issues.length > 0) throw new InterfaceError(issues);
  return {
    [APP_DECLARATIONS_PATH]: renderDeclarations(
      declared.declarations,
      inputs.commands,
      "@bdk/internal",
    ),
    [APP_AUTOMATION_PATH]: renderDeclarations(
      declared.declarations,
      inputs.commands,
      "@bdk/automation",
    ),
    [APP_ENVIRONMENT_PATH]: renderEnvironment(environment.environment, inputs.resolved),
  };
}
