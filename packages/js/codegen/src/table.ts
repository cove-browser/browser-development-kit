/**
 * Renders the C++ tables the broker reads: every type, command and event with its identifier, and the
 * policy lists. Same definitions and registry in, same bytes out.
 */
export function renderCommandTable(
  definitions: Definitions,
  registry: Registry,
  policy: Policy,
): string {
  const typeIndex = new Map(definitions.types.map((type, index) => [type.name, index] as const));
  const surfaces = new Map<string, number>();
  for (const group of definitions.constants) {
    if (group.group !== "surfaces") continue;
    for (const [suffix, value] of group.values) surfaces.set(suffix.toLowerCase(), Number(value));
  }
  const idOf = (entries: Registry["commands"], name: string): number =>
    Number(entries.find((entry) => entry.name === name && entry.retired !== true)?.id);

  const out: string[] = [];
  const typeRows = definitions.types.map((type, index) => typeRow(type, index, typeIndex, out));
  out.push("inline constexpr TypeDef kTypes[] = {");
  for (const row of typeRows) out.push(`    ${row},`);
  if (typeRows.length === 0) {
    out.push(`    {nullptr, Kind::kAlias, nullptr, 0, nullptr, 0, ${VOID_REF}},`);
  }
  out.push("};", `inline constexpr size_t kTypeCount = ${typeRows.length};`, "");

  const commands = [...definitions.commands].sort(
    (a, b) => idOf(registry.commands, a.name) - idOf(registry.commands, b.name),
  );
  const commandRows = commands.map((command, index) => {
    const args = fieldArray(`kArgs${index}`, command.args, typeIndex, out);
    const callers = command.callers.reduce((bits, caller) => bits | CALLER_BITS[caller], 0);
    const raises = command.raises === undefined ? 0 : (surfaces.get(command.raises) ?? 0);
    const when =
      command.authenticateWhen === undefined ? "nullptr" : cString(command.authenticateWhen);
    const capability = command.capability === undefined ? "nullptr" : cString(command.capability);
    const id = idOf(registry.commands, command.name);
    return `{${id}u, ${cString(command.name)}, ${capability}, ${callers}, ${PROFILE_MODES[command.profile]}, ${flagsOf(command)}, ${raises}, ${when}, ${args}, ${command.args.length}}`;
  });
  out.push("", "inline constexpr CommandDef kCommands[] = {");
  for (const row of commandRows) out.push(`    ${row},`);
  if (commandRows.length === 0) {
    out.push("    {0, nullptr, nullptr, 0, 0, 0, 0, nullptr, nullptr, 0},");
  }
  out.push("};", `inline constexpr size_t kCommandCount = ${commandRows.length};`, "");

  const events = [...definitions.events].sort(
    (a, b) => idOf(registry.events, a.name) - idOf(registry.events, b.name),
  );
  out.push("inline constexpr EventDef kEvents[] = {");
  for (const event of events) {
    const id = idOf(registry.events, event.name);
    out.push(`    {${id}u, ${cString(event.name)}, ${cString(event.capability)}},`);
  }
  if (events.length === 0) out.push("    {0, nullptr, nullptr},");
  out.push("};", `inline constexpr size_t kEventCount = ${events.length};`, "");

  out.push(...patterns("kNeverForPages", policy.neverForPages));
  out.push(...patterns("kNeverForSessions", policy.neverForSessions));

  const lines = [
    ...HEAD,
    ...out,
    "",
    "} // namespace bdkcore::table",
    "",
    "#endif /* BDK_COMMAND_TABLE_INC_ */",
  ];
  return `${lines.join("\n")}\n`;
}
