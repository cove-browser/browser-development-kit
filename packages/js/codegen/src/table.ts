import type { Command, Definitions, FieldDefinition, Policy, TypeDefinition } from "./model.js";
import { PRIMITIVES } from "./model.js";
import type { Registry } from "./registry.js";

/** Where the broker's tables are written, relative to `packages/core`. */
export const TABLE_PATH = "generated/bdk_command_table.inc";

const CALLER_BITS = { swift: 1, page: 2, session: 4 } as const;
const PROFILE_MODES = { none: 0, optional: 1, required: 2 } as const;
/** C++ names of the primitive types, in the order of `PRIMITIVES`. */
const PRIMITIVE_NAMES = [
  "kString",
  "kInt",
  "kDouble",
  "kBool",
  "kUrl",
  "kTimestamp",
  "kBytes",
  "kJson",
] as const;
const VOID_REF = "{Prim::kVoid, 0, false, false}";

function cString(text: string): string {
  return JSON.stringify(text);
}

/** `{prim, type, array, optional}` for a type expression such as `HistoryEntry[]?`. */
function typeRef(expression: string, typeIndex: ReadonlyMap<string, number>): string {
  const optional = expression.endsWith("?");
  const bare = optional ? expression.slice(0, -1) : expression;
  const array = bare.endsWith("[]");
  const base = array ? bare.slice(0, -2) : bare;
  const prim = PRIMITIVES.indexOf(base);
  if (prim >= 0) return `{Prim::${PRIMITIVE_NAMES[prim]}, 0, ${array}, ${optional}}`;
  return `{Prim::kNamed, ${typeIndex.get(base)}, ${array}, ${optional}}`;
}

function fieldArray(
  name: string,
  fields: readonly FieldDefinition[],
  typeIndex: ReadonlyMap<string, number>,
  out: string[],
): string {
  if (fields.length === 0) return "nullptr";
  out.push(`inline constexpr Field ${name}[] = {`);
  for (const field of fields) {
    out.push(`    {${cString(field.name)}, ${typeRef(field.type, typeIndex)}},`);
  }
  out.push("};");
  return name;
}

function typeRow(
  type: TypeDefinition,
  index: number,
  typeIndex: ReadonlyMap<string, number>,
  out: string[],
): string {
  const name = cString(type.name);
  if (type.kind === "struct") {
    const fields = fieldArray(`kTypeFields${index}`, type.fields, typeIndex, out);
    return `{${name}, Kind::kStruct, ${fields}, ${type.fields.length}, nullptr, 0, ${VOID_REF}}`;
  }
  if (type.kind === "enum") {
    out.push(`inline constexpr const char* kTypeValues${index}[] = {`);
    for (const value of type.values) out.push(`    ${cString(value)},`);
    out.push("};");
    return `{${name}, Kind::kEnum, nullptr, 0, kTypeValues${index}, ${type.values.length}, ${VOID_REF}}`;
  }
  return `{${name}, Kind::kAlias, nullptr, 0, nullptr, 0, ${typeRef(type.target, typeIndex)}}`;
}

function flagsOf(command: Command): string {
  const flags: string[] = [];
  if (command.requires.includes("gesture")) flags.push("kGesture");
  if (command.requires.includes("authentication")) flags.push("kAuthentication");
  if (command.paginated) flags.push("kPaginated");
  if (command.progress) flags.push("kProgress");
  if (command.stream) flags.push("kStream");
  if (command.binary) flags.push("kBinary");
  return flags.length === 0 ? "0" : flags.join(" | ");
}

function patterns(name: string, list: readonly string[]): string[] {
  return [
    `inline constexpr const char* ${name}[] = {`,
    ...list.map((entry) => `    ${cString(entry)},`),
    "    nullptr,",
    "};",
  ];
}

