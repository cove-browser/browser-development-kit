import { describe, expect, it } from "vitest";
import {
  APP_DECLARATIONS_PATH,
  APP_ENVIRONMENT_PATH,
  type ApplicationInputs,
  digestOf,
  generateApplication,
  isStale,
  readDigest,
} from "./application.js";
import { InterfaceError } from "./issue.js";
import { type Json, mutate } from "./test-support.js";

function declarations(): Json {
  return {
    version: 1,
    commands: [
      {
        name: "app.notes.create",
        capability: "app.notes.create",
        callers: ["swift", "page", "session"],
        profile: "required",
        args: { title: "string", body: "string?", tags: "string[]?" },
        result: "Note",
        types: {
          Note: { id: "string", title: "string", color: "Color", extra: "json?" },
          Color: { enum: ["red", "blue"] },
        },
      },
      {
        name: "app.notes.clear",
        capability: "app.notes.clear",
        callers: ["swift", "page", "session"],
        profile: "required",
        args: "void",
        result: "void",
        requires: ["gesture"],
      },
      {
        name: "app.tabs.open",
        capability: "app.tabs.open",
        callers: ["swift", "page", "session"],
        profile: "none",
        args: { url: "url", background: "bool?" },
        result: { id: "string" },
      },
    ],
    events: [
      {
        name: "app.notes.changed",
        capability: "app.notes.changed",
        payload: { id: "string", note: "Note?" },
        types: { Note: { id: "string", title: "string", color: "Color", extra: "json?" } },
      },
      { name: "app.notes.cleared", capability: "app.notes.cleared", payload: "void" },
    ],
    settings: [
      {
        key: "app.theme",
        type: "string",
        default: "light",
        scope: "profile",
        exposedToPages: true,
      },
      { key: "app.secret", type: "string", default: "", scope: "profile", exposedToPages: false },
      { key: "app.layout", type: "object", default: {}, scope: "profile", exposedToPages: true },
      { key: "app.last", type: "json", default: null, scope: "application", exposedToPages: true },
    ],
  };
}

function resolved(): Json {
  return {
    schema: 1,
    browser: { name: "Cove", internal_scheme: "cove" },
    routes: {
      agents: { mode: "bundled", path: "Pages/Agents", capabilities: ["app.agents.*"] },
      "new-tab": { mode: "bundled", path: "Pages/NewTab", capabilities: [] },
    },
    aliases: { bots: "agents", zeta: "agents" },
  };
}

function inputs(commands: Json = declarations(), config: Json = resolved()): ApplicationInputs {
  return { commands: JSON.stringify(commands), resolved: JSON.stringify(config) };
}

const generate = (commands?: Json, config?: Json): Record<string, string> =>
  generateApplication(inputs(commands, config));

function issues(commands?: Json, config?: Json): string[] {
  try {
    generate(commands, config);
  } catch (error) {
    if (error instanceof InterfaceError) return error.message.split("\n");
    throw error;
  }
  return [];
}

describe("generateApplication", () => {
  it("writes app.d.ts and env.d.ts", () => {
    expect(Object.keys(generate()).sort()).toEqual([APP_ENVIRONMENT_PATH, APP_DECLARATIONS_PATH]);
    expect(APP_DECLARATIONS_PATH).toBe("@bdk/internal/app.d.ts");
    expect(APP_ENVIRONMENT_PATH).toBe("@bdk/env.d.ts");
  });

  it("is byte-stable", () => {
    expect(generate()).toEqual(generate());
  });

  it("writes the application's commands, events and settings as module augmentations", () => {
    expect(generate()[APP_DECLARATIONS_PATH]).toMatchInlineSnapshot(`
      "// Generated by @bdk/codegen from bdk.commands.json. Do not edit.
      // Regenerate with: bdk build codegen
      // Input digest: sha256:bb8c84b541019adebbae3124ad9ab2698476ce178d08412b0ab38e5e09445a8e
      // biome-ignore-all lint: generated file
      // biome-ignore-all format: generated file

      import type { JsonValue } from "@bdk/internal/types";

      export {};

      export type Color = "red" | "blue";

      export interface Note {
        id: string;
        title: string;
        color: Color;
        extra?: JsonValue | null;
      }

      declare module "@bdk/internal/commands" {
        interface AppCommands {
          "app.notes.create": { input: { title: string; body?: string; tags?: string[]; }; output: Note };
          "app.notes.clear": { input: Record<string, never>; output: void };
          "app.tabs.open": { input: { url: string; background?: boolean; }; output: { id: string; } };
        }
      }

      declare module "@bdk/internal/events" {
        interface AppEvents {
          "app.notes.changed": { id: string; note?: Note | null; };
          "app.notes.cleared": Record<string, never>;
        }
      }

      declare module "@bdk/internal/app-settings" {
        interface AppSettings {
          "app.theme": string;
          "app.layout": { [key: string]: JsonValue };
          "app.last": JsonValue;
        }
      }
      "
    `);
  });

  it("writes the route names, aliases included, and the internal scheme", () => {
    expect(generate()[APP_ENVIRONMENT_PATH]).toMatchInlineSnapshot(`
      "// Generated by @bdk/codegen from bdk.resolved.json. Do not edit.
      // Regenerate with: bdk build codegen
      // Input digest: sha256:38e074c01fff54df16efb56e1b401df6f67ea775c9334402a9be3bf4ebe52bf6
      // biome-ignore-all lint: generated file
      // biome-ignore-all format: generated file

      /** Every route name and alias of the application, as \`page.url\` takes them. */
      export type RouteName = "agents" | "bots" | "new-tab" | "zeta";

      /** The branded scheme of the application's internal pages. */
      export type InternalScheme = "cove";
      "
    `);
  });

  it("writes never when there are no routes, and omits what is not declared", () => {
    const files = generate(
      { version: 1, commands: [], events: [] },
      { browser: { internal_scheme: "x" }, routes: {} },
    );
    expect(files[APP_ENVIRONMENT_PATH]).toContain("export type RouteName = never;");
    const app = files[APP_DECLARATIONS_PATH] as string;
    expect(app).toContain("export {};");
    expect(app).not.toContain("declare module");
    expect(app).not.toContain("import type");
  });

  it("accepts an older file without settings", () => {
    const old = mutate(declarations(), (file) => {
      delete file.settings;
    });
    expect(generate(old)[APP_DECLARATIONS_PATH]).not.toContain("app-settings");
  });
});

describe("the digest", () => {
  it("is the SHA-256 of the input, as sha256:<hex>", () => {
    expect(digestOf("abc")).toBe(
      "sha256:ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
    );
  });

  it("is in the header of each file and read back from it", () => {
    const input = inputs();
    const files = generateApplication(input);
    const app = files[APP_DECLARATIONS_PATH] as string;
    const env = files[APP_ENVIRONMENT_PATH] as string;
    expect(
      app.startsWith("// Generated by @bdk/codegen from bdk.commands.json. Do not edit.\n"),
    ).toBe(true);
    expect(
      env.startsWith("// Generated by @bdk/codegen from bdk.resolved.json. Do not edit.\n"),
    ).toBe(true);
    expect(readDigest(app)).toBe(digestOf(input.commands));
    expect(readDigest(env)).toBe(digestOf(input.resolved));
  });

  it("is undefined for a file that has none", () => {
    expect(readDigest("export {};\n")).toBeUndefined();
    expect(readDigest("// Input digest: sha256:short\n")).toBeUndefined();
  });

  it("tells a build whether the declarations are stale", () => {
    const input = inputs();
    const app = generateApplication(input)[APP_DECLARATIONS_PATH] as string;
    expect(isStale(app, input.commands)).toBe(false);
    const changed = JSON.stringify(
      mutate(declarations(), (file) => {
        (file.commands as Json[]).pop();
      }),
    );
    expect(isStale(app, changed)).toBe(true);
    expect(isStale("export {};\n", input.commands)).toBe(true);
  });

  it("changes with the input: a changed command changes app.d.ts and its digest, not env.d.ts", () => {
    const before = generate();
    const after = generate(
      mutate(declarations(), (file) => {
        ((file.commands as Json[])[0] as Json).args = { title: "string" };
      }),
    );
    expect(after[APP_DECLARATIONS_PATH]).not.toBe(before[APP_DECLARATIONS_PATH]);
    expect(readDigest(after[APP_DECLARATIONS_PATH] as string)).not.toBe(
      readDigest(before[APP_DECLARATIONS_PATH] as string),
    );
    expect(after[APP_DECLARATIONS_PATH]).not.toContain("body?: string");
    expect(after[APP_ENVIRONMENT_PATH]).toBe(before[APP_ENVIRONMENT_PATH]);
  });

  it("changes env.d.ts when a route is added, not app.d.ts", () => {
    const before = generate();
    const after = generate(
      undefined,
      mutate(resolved(), (file) => {
        (file.routes as Json).history = { capabilities: [] };
      }),
    );
    expect(after[APP_ENVIRONMENT_PATH]).toContain('"history"');
    expect(after[APP_DECLARATIONS_PATH]).toBe(before[APP_DECLARATIONS_PATH]);
  });
});

describe("validation", () => {
  it("accepts the fixture", () => {
    expect(issues()).toEqual([]);
  });

  it("names the file and path of each problem", () => {
    const broken = mutate(declarations(), (file) => {
      ((file.commands as Json[])[0] as Json).name = "history.search";
    });
    expect(issues(broken)).toEqual([
      'bdk.commands.json: $.commands[0].name: command names start with "app." and have lower-camel-case segments',
    ]);
  });

  it("throws an InterfaceError carrying Issue objects", () => {
    const broken = mutate(declarations(), (file) => {
      file.version = 2;
    });
    try {
      generate(broken);
      expect.unreachable();
    } catch (error) {
      expect(error).toBeInstanceOf(InterfaceError);
      expect((error as InterfaceError).issues).toEqual([
        { file: "bdk.commands.json", path: "$.version", message: "must be 1" },
      ]);
    }
  });

  it.each([
    ["a name without the app. prefix", "name", "notes.create", "$.commands[0].name"],
    ["the bare prefix", "name", "app", "$.commands[0].name"],
    ["an upper-case segment", "name", "app.Notes.create", "$.commands[0].name"],
  ])("rejects %s", (_, key, value, path) => {
    const broken = mutate(declarations(), (file) => {
      ((file.commands as Json[])[0] as Json)[key] = value;
    });
    expect(issues(broken)[0]).toContain(path);
  });

  it("rejects an event or a setting outside app.", () => {
    const event = mutate(declarations(), (file) => {
      ((file.events as Json[])[0] as Json).name = "history.visited";
    });
    expect(issues(event)[0]).toContain("$.events[0].name: event names start with");
    const setting = mutate(declarations(), (file) => {
      ((file.settings as Json[])[0] as Json).key = "theme";
    });
    expect(issues(setting)[0]).toContain("$.settings[0].key: setting keys start with");
  });

  it("rejects duplicates", () => {
    const duplicate = mutate(declarations(), (file) => {
      (file.commands as Json[]).push(structuredClone((file.commands as Json[])[2] as Json));
    });
    expect(issues(duplicate)).toEqual([
      'bdk.commands.json: $.commands[3].name: duplicate command "app.tabs.open"',
    ]);
  });

  it("rejects a type that is not defined, a bad expression and a bad shape", () => {
    const unknown = mutate(declarations(), (file) => {
      ((file.commands as Json[])[2] as Json).result = { note: "Missing" };
    });
    expect(issues(unknown)).toEqual([
      'bdk.commands.json: $.commands[2].result.note: unknown type "Missing"',
    ]);
    const expression = mutate(declarations(), (file) => {
      ((file.commands as Json[])[2] as Json).args = { url: "url??" };
    });
    expect(issues(expression)[0]).toContain('"url??" is not a type expression');
    const shape = mutate(declarations(), (file) => {
      ((file.commands as Json[])[2] as Json).args = 5;
    });
    expect(issues(shape)[0]).toContain("$.commands[2].args: must be a type expression string");
  });

  it("rejects a type declared two ways, and a reserved or malformed type name", () => {
    const clash = mutate(declarations(), (file) => {
      (((file.events as Json[])[0] as Json).types as Json).Note = { id: "int" };
    });
    expect(issues(clash)).toEqual([
      'bdk.commands.json: $.events[0].types.Note: type "Note" is declared differently at $.commands[0].types.Note',
    ]);
    const reserved = mutate(declarations(), (file) => {
      (((file.commands as Json[])[0] as Json).types as Json).JsonValue = { a: "int" };
    });
    expect(issues(reserved)[0]).toContain('"JsonValue" is not a usable type name');
    const lower = mutate(declarations(), (file) => {
      (((file.commands as Json[])[0] as Json).types as Json).note = { a: "int" };
    });
    expect(issues(lower)[0]).toContain('"note" is not a usable type name');
  });

  it("rejects a setting of an unknown type", () => {
    const broken = mutate(declarations(), (file) => {
      ((file.settings as Json[])[0] as Json).type = "date";
    });
    expect(issues(broken)[0]).toContain("$.settings[0].type: must be one of");
  });

  it("rejects unknown top-level fields and a top level that is not an object", () => {
    const extra = mutate(declarations(), (file) => {
      file.extra = 1;
    });
    expect(issues(extra)).toEqual(["bdk.commands.json: $.extra: unknown field"]);
    expect(() => generateApplication({ commands: "[]", resolved: inputs().resolved })).toThrowError(
      "bdk.commands.json: $: must be an object",
    );
  });

  it("reports invalid JSON in either file, and every problem at once", () => {
    const error = (() => {
      try {
        generateApplication({ commands: "{", resolved: "nope" });
      } catch (e) {
        return e as InterfaceError;
      }
      throw new Error("did not throw");
    })();
    expect(error.issues.map((issue) => `${issue.file} ${issue.path}`)).toEqual([
      "bdk.commands.json $",
      "bdk.resolved.json $",
    ]);
    expect(error.message).toMatch(/^bdk\.commands\.json: \$: invalid JSON: /);
  });

  it("rejects a resolved file without routes or without the internal scheme", () => {
    const noRoutes = mutate(resolved(), (file) => {
      delete file.routes;
    });
    expect(issues(undefined, noRoutes)).toEqual(["bdk.resolved.json: $.routes: must be an object"]);
    const noScheme = mutate(resolved(), (file) => {
      file.browser = {};
    });
    expect(issues(undefined, noScheme)).toEqual([
      "bdk.resolved.json: $.browser.internal_scheme: must be the internal scheme, a non-empty string",
    ]);
  });
});
