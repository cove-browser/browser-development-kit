import { describe, expect, it } from "vitest";
import { build, type Inputs } from "./generate.js";
import { NATIVE_NAMESPACES } from "./swift.js";
import { abi, history, type Json, mutate } from "./test-support.js";

const POLICY = JSON.stringify({ neverForPages: ["contents.*"], neverForSessions: [] });
const ALL = ["swift", "page", "session"];

function command(name: string, extra: Json = {}): Json {
  return {
    name,
    capability: `${name.split(".")[0]}.read`,
    callers: ALL,
    profile: "required",
    args: {},
    result: "void",
    ...extra,
  };
}

/** A set that exercises every shape the generator has a rule for. */
function extras(): Json[] {
  return [
    {
      namespace: "settings",
      since: 1,
      types: { SettingInfo: { key: "string", default: "json", allowed: "json?" } },
      commands: [
        command("settings.get", {
          profile: "optional",
          args: { key: "string" },
          result: { value: "json" },
        }),
        command("settings.describe", {
          profile: "optional",
          args: { key: "string" },
          result: "SettingInfo",
        }),
      ],
      events: [
        {
          name: "settings.changed",
          capability: "settings.read",
          payload: { key: "string", source: "ChangeSource" },
        },
      ],
    },
    {
      namespace: "privacy",
      since: 1,
      types: { PrivacyType: { enum: ["history", "default"] } },
      commands: [
        command("privacy.clear", {
          requires: ["gesture"],
          progress: true,
          args: { types: "PrivacyType[]", range: "TimeRange?" },
        }),
        command("privacy.check", {
          requires: ["authentication"],
          result: { checked: "int", flagged: "int" },
        }),
      ],
      events: [{ name: "privacy.refreshed", capability: "privacy.read", payload: {} }],
    },
    {
      namespace: "autofill",
      since: 1,
      commands: [
        command("autofill.cards.list", { result: { items: "string[]" } }),
        command("autofill.cards.remove", { args: { id: "string" } }),
      ],
    },
    {
      namespace: "runtime",
      since: 1,
      commands: [command("runtime.info", { profile: "none", result: "string" })],
    },
    {
      namespace: "profiles",
      since: 1,
      commands: [command("profiles.list", { profile: "none", result: "string" })],
    },
    {
      namespace: "bookmarks",
      since: 1,
      commands: [
        command("bookmarks.create", {
          args: { parentId: "string", index: "int?", title: "string", url: "url" },
          result: "string",
        }),
        command("bookmarks.move", {
          args: { id: "string", parentId: "string", index: "int?" },
        }),
      ],
    },
  ];
}

function inputs(files: Json[] = extras(), historyFile: Json = history()): Inputs {
  return {
    abiVersion: 1,
    definitions: [
      { file: "history.json", text: JSON.stringify(historyFile) },
      { file: "abi.json", text: JSON.stringify(abi()) },
      ...files.map((file) => ({ file: `${file.namespace}.json`, text: JSON.stringify(file) })),
    ],
    policy: POLICY,
    registry: undefined,
  };
}

const swift = (files?: Json[], historyFile?: Json): string =>
  build(inputs(files, historyFile)).swift;

describe("the Swift wrappers", () => {
  it("is byte-stable and independent of the order of the files", () => {
    const first = swift();
    expect(swift()).toBe(first);
    const reversed = { ...inputs(), definitions: [...inputs().definitions].reverse() };
    expect(build(reversed).swift).toBe(first);
  });

  it("starts with the generated-file markers and is excluded from the formatters", () => {
    expect(swift().startsWith("// swift-format-ignore-file\n// Generated by")).toBe(true);
    expect(swift()).toContain(
      "// Generated by packages/js/codegen from packages/core/interface. Do not edit.",
    );
  });

  it("writes structs and enums for the named types, optional fields defaulting to nil", () => {
    const out = swift();
    expect(out).toContain(
      [
        "public struct BDKTimeRange: Codable, Sendable, Equatable {",
        "    public var start: Date?",
        "    public var end: Date?",
        "",
        "    public init(",
        "        start: Date? = nil,",
        "        end: Date? = nil",
        "    ) {",
        "        self.start = start",
        "        self.end = end",
        "    }",
        "}",
      ].join("\n"),
    );
    expect(out).toContain(
      "public enum BDKChangeSource: String, Codable, Sendable, Equatable, CaseIterable {",
    );
    expect(out).toContain("    case user\n    case sync\n");
  });

  it("escapes Swift keywords in field names and enum cases", () => {
    const out = swift();
    expect(out).toContain("    public var `default`: BDKJSValue");
    expect(out).toContain("    case `default`\n");
    expect(out).toContain("    public var allowed: BDKJSValue?");
  });

  it("makes a method per command, with a result struct for several fields", () => {
    const out = swift();
    expect(out).toContain("public struct BDKHistory {");
    expect(out).toContain(
      [
        "    public func search(",
        "        _ text: String,",
        "        in range: BDKTimeRange? = nil,",
        "        limit: Int? = nil,",
        "        cursor: String? = nil",
        "    ) async throws -> SearchResult {",
      ].join("\n"),
    );
    expect(out).toContain("    public struct SearchResult: Codable, Sendable, Equatable {");
    expect(out).toContain("        public var nextCursor: String?");
    expect(out).toContain('try await scope.call("history.search", Arguments(');
    expect(out).toContain(
      "Paginated: pass the returned `nextCursor` as `cursor` for the next page.",
    );
  });

  it("returns the one field of a single-field result directly, and nothing for void", () => {
    const out = swift();
    expect(out).toContain("    ) async throws -> BDKJSValue {");
    expect(out).toContain(".value\n    }");
    expect(out).toContain(
      [
        "    public func deleteAll() async throws {",
        '        try await scope.run("history.deleteAll", BDKVoid())',
      ].join("\n"),
    );
  });

  it("applies the name, label and order rules", () => {
    const out = swift();
    expect(out).toContain(
      "    public func get(\n        _ key: String\n    ) async throws -> BDKJSValue {",
    );
    expect(out).toContain(
      [
        "    public func create(",
        "        url: URL,",
        "        title: String,",
        "        in parentId: String,",
        "        at index: Int? = nil",
        "    ) async throws -> String {",
      ].join("\n"),
    );
    expect(out).toContain(
      "    public func move(\n        _ id: String,\n        to parentId: String,\n        at index: Int? = nil\n    ) async throws {",
    );
  });

  it("names a command renamed for Swift by its Swift name only", () => {
    const withDelete = mutate(history(), (f) => {
      (f.commands as unknown[]).push(
        command("history.deleteUrls", { args: { urls: "url[]" }, capability: "history.write" }),
      );
    });
    const out = swift(extras(), withDelete);
    expect(out).toContain("    public func delete(\n        urls: [URL]\n    ) async throws {");
    expect(out).toContain('scope.run("history.deleteUrls", Arguments(urls: urls))');
  });

  it("documents gesture, authentication and progress, and adds a progress parameter", () => {
    const out = swift();
    expect(out).toContain("/// `privacy.clear`.");
    expect(out).toContain(
      "A page must have been given a user gesture to call it; a call from Swift needs none.",
    );
    expect(out).toContain(
      "Asks the operating system to authenticate (Touch ID or the login password)",
    );
    expect(out).toContain(
      "        onProgress: (@MainActor (Double, String) -> Void)? = nil\n    ) async throws {",
    );
    expect(out).toContain(
      'try await scope.run("privacy.clear", Arguments(types: types, range: range), onProgress: onProgress)',
    );
  });

  it("nests a group as its own service", () => {
    const out = swift();
    expect(out).toContain("public struct BDKAutofill {");
    expect(out).toContain(
      "    public var cards: BDKAutofillCards {\n        BDKAutofillCards(scope: scope)\n    }",
    );
    expect(out).toContain("public struct BDKAutofillCards {");
    expect(out).toContain("    public func remove(\n        _ id: String\n    ) async throws {");
  });

  it("hangs a namespace on the profile, the runtime, or both, by its profile mode", () => {
    const out = swift();
    const profileBlock = out.slice(
      out.indexOf("extension BDKProfile {"),
      out.indexOf("extension BDKRuntime {"),
    );
    const runtimeBlock = out.slice(out.indexOf("extension BDKRuntime {"));
    expect(profileBlock).toContain("public var history: BDKHistory {");
    expect(profileBlock).toContain("public var settings: BDKSettings {");
    expect(profileBlock).toContain("BDKServiceScope(runtime: runtime, profile: self)");
    expect(profileBlock).not.toContain("about");
    expect(runtimeBlock).toContain("public var settings: BDKSettings {");
    expect(runtimeBlock).toContain("BDKServiceScope(runtime: self, profile: nil)");
    expect(runtimeBlock).toContain("public var about: BDKRuntimeInformation {");
    expect(runtimeBlock).not.toContain("public var history");
  });

  it("generates nothing for the namespaces the Swift layer implements itself", () => {
    expect(NATIVE_NAMESPACES).toEqual(["profiles"]);
    const out = swift();
    expect(out).not.toContain("BDKProfiles");
    expect(out).not.toContain("profiles.list");
  });

  it("skips a command that Swift may not call", () => {
    const pageOnly = mutate(history(), (f) => {
      ((f.commands as Record<string, unknown>[])[0] as Record<string, unknown>).callers = [
        "page",
        "session",
      ];
    });
    expect(swift(extras(), pageOnly)).not.toContain("history.search");
  });

  it("writes an event enum with a payload struct per event and a decoder by name", () => {
    const out = swift();
    expect(out).toContain("    public enum Event: Sendable, Equatable {");
    expect(out).toContain("        case visited(Visited)");
    expect(out).toContain("        public struct Visited: Codable, Sendable, Equatable {");
    expect(out).toContain("            public var entry: BDKHistoryEntry");
    expect(out).toContain('        static let names = ["history.visited"]');
    expect(out).toContain(
      'case "history.visited":\n                return .visited(try BDKServiceCoding.decode(Visited.self, from: payload))',
    );
    expect(out).toContain(
      "    public var events: AsyncStream<Event> {\n        scope.events(Event.names, decode: Event.decode)",
    );
  });

  it("writes an event with no payload as a bare case", () => {
    const out = swift();
    expect(out).toContain("        case refreshed\n");
    expect(out).toContain('case "privacy.refreshed":\n                return .refreshed');
  });

  it("changes when a definition changes", () => {
    const changed = mutate(history(), (f) => {
      (
        ((f.commands as Record<string, unknown>[])[0] as Record<string, unknown>).args as Json
      ).extra = "bool?";
    });
    expect(swift(extras(), changed)).not.toBe(swift());
    expect(swift(extras(), changed)).toContain("        extra: Bool? = nil");
  });

  it("refuses a namespace that mixes commands with and without a profile", () => {
    const mixed = mutate(history(), (f) => {
      (f.commands as unknown[]).push(command("history.where", { profile: "none" }));
    });
    expect(() => swift(extras(), mixed)).toThrow(/cannot share a namespace/);
  });
});
